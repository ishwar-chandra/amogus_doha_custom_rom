#!/usr/bin/env python3
"""Add only the BSNL IMS APNs that the synced vendor/apn tree lacks.

The APN database is version-dependent: some LineageOS pins ship no BSNL IMS
row, newer ones ship them for every mcc=404 BSNL MNC. This tool reads the
actual synced tree and adds a missing `type="ims"` row per MNC, preserving the
upstream rows instead of duplicating them.

Layouts handled:
  A) vendor/apn/upstream/apns-conf.xml + root *.xml merged by local_apns_conf
     (current LineageOS). Writes bsnl_ims_missing.xml at the repo root.
  B) vendor/apn/IN.xml (older pin). Inserts rows before </apns>.

Exit code is 0 even when nothing is missing; the build does not depend on it.
"""
from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

MCC = "404"
BSNL_CARRIER_ID = "1549"


def is_bsnl(row: dict[str, str]) -> bool:
    text = " ".join(
        row.get(k, "") for k in ("carrier", "apn")
    ).lower()
    return row.get("carrier_id") == BSNL_CARRIER_ID or "bsnl" in text or "cellone" in text


def rows_of(path: Path) -> list[dict[str, str]]:
    return [e.attrib for e in ET.parse(path).getroot().findall("apn")]


def apn_version(path: Path) -> str:
    return ET.parse(path).getroot().get("version", "8")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    apn = Path(sys.argv[1])
    if not apn.is_dir():
        print(f"fix_apn: {apn} is not a directory", file=sys.stderr)
        return 2

    upstream = apn / "upstream" / "apns-conf.xml"
    legacy = apn / "IN.xml"
    source = upstream if upstream.is_file() else legacy if legacy.is_file() else None
    if source is None:
        print("fix_apn: no upstream/apns-conf.xml or IN.xml; nothing to do")
        return 0

    rows = rows_of(source)
    bsnl = [r for r in rows if r.get("mcc") == MCC and is_bsnl(r)]
    all_mncs = sorted({r["mnc"] for r in bsnl if r.get("mnc")}, key=lambda x: int(x))
    have_ims = {
        r["mnc"]
        for r in bsnl
        if r.get("mnc") and "ims" in (r.get("type") or "").split(",")
    }
    missing = [m for m in all_mncs if m not in have_ims]

    version = apn_version(source)
    generated = apn / "bsnl_ims_missing.xml"

    if not missing:
        if generated.exists():
            generated.unlink()
        print(f"fix_apn: all {len(all_mncs)} BSNL MNCs already have an IMS row")
        return 0

    def row(mnc: str) -> str:
        return (
            f'    <apn carrier="BSNL IMS" mcc="{MCC}" mnc="{mnc}" '
            f'apn="ims" type="ims" carrier_id="{BSNL_CARRIER_ID}" '
            f'protocol="IPV4V6" roaming_protocol="IPV4V6" />\n'
        )

    body = "".join(row(m) for m in missing)

    # Layout A: root file is merged by the local_apns_conf filegroup.
    android_bp = apn / "Android.bp"
    has_local_filegroup = (
        android_bp.is_file()
        and 'srcs: ["*.xml"]' in android_bp.read_text()
    )
    if has_local_filegroup:
        generated.write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- generated by fix_apn.py: BSNL IMS rows missing upstream -->\n'
            f'<apns version="{version}">\n{body}</apns>\n'
        )
        print(f"fix_apn: wrote {generated} for MNCs {', '.join(missing)}")
        return 0

    # Layout B: older single-file IN.xml. Insert before the closing tag.
    if legacy.is_file():
        text = legacy.read_text()
        if "</apns>" in text:
            text = text.replace("</apns>", body + "</apns>", 1)
            legacy.write_text(text)
            print(f"fix_apn: inserted IMS rows into {legacy} for MNCs {', '.join(missing)}")
            return 0

    print(
        "fix_apn: unknown vendor/apn layout; add an IMS APN for BSNL MNCs "
        + ", ".join(missing),
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
